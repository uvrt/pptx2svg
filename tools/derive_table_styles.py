EMPTY_TREE = (
    '<p:spTree><p:nvGrpSpPr><p:cNvPr id="0" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
    '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/>'
    '<a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr></p:spTree>'
)
NAMESPACES = (
    'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
    'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
    'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"'
)
CONTENT_TYPE_SLIDE = (
    "application/vnd.openxmlformats-officedocument.presentationml.slide+xml"
)


def background(hex_rgb: str) -> str:
    return (
        f'<p:bg><p:bgPr><a:solidFill><a:srgbClr val="{hex_rgb}"/></a:solidFill>'
        "<a:effectLst/></p:bgPr></p:bg>"
    )


def slide_document(backdrop: str, body: str) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        f"<p:sld {NAMESPACES}><p:cSld>"
        + background(backdrop)
        + '<p:spTree><p:nvGrpSpPr><p:cNvPr id="0" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
        '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/>'
        '<a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>'
        + body
        + "</p:spTree></p:cSld>"
        "<p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr></p:sld>"
    )


def blank_template(xml: str, backdrop: str) -> str:
    """Empty a layout or master so nothing shows through an unfilled table cell."""
    xml = re.sub(r"<p:spTree>.*?</p:spTree>", EMPTY_TREE, xml, flags=re.S)
    xml = re.sub(r"<p:bg>.*?</p:bg>", "", xml, flags=re.S)
    return xml.replace("<p:cSld>", "<p:cSld>" + background(backdrop), 1)


def write_deck(source: Path, target: Path, slides: list[str], backdrop: str) -> None:
    """Clone a deck, replacing its slides with the given ones."""
    zin = zipfile.ZipFile(source)
    base_rels = zin.read("ppt/slides/_rels/slide1.xml.rels")
    presentation = zin.read("ppt/presentation.xml").decode()
    pres_rels = zin.read("ppt/_rels/presentation.xml.rels").decode()
    content_types = zin.read("[Content_Types].xml").decode()

    numbers = range(1, len(slides) + 1)
    sld_ids = "".join(f'<p:sldId id="{255 + n}" r:id="rIdS{n}"/>' for n in numbers)
    presentation = re.sub(
        r"<p:sldIdLst>.*?</p:sldIdLst>",
        f"<p:sldIdLst>{sld_ids}</p:sldIdLst>",
        presentation,
        flags=re.S,
    )

    rel_type = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide"
    pres_rels = re.sub(r'<Relationship[^>]*Type="[^"]*/slide"[^>]*/>', "", pres_rels)
    pres_rels = pres_rels.replace(
        "</Relationships>",
        "".join(
            f'<Relationship Id="rIdS{n}" Type="{rel_type}" Target="slides/slide{n}.xml"/>'
            for n in numbers
        )
        + "</Relationships>",
    )

    content_types = re.sub(
        r'<Override PartName="/ppt/slides/slide\d+\.xml"[^>]*/>', "", content_types
    )
    content_types = content_types.replace(
        "</Types>",
        "".join(
            f'<Override PartName="/ppt/slides/slide{n}.xml" ContentType="{CONTENT_TYPE_SLIDE}"/>'
            for n in numbers
        )
        + "</Types>",
    )

    target.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            if item.filename.startswith("ppt/slides/"):
                continue
            data = zin.read(item.filename)
            if item.filename == "ppt/presentation.xml":
                data = presentation.encode()
            elif item.filename == "ppt/_rels/presentation.xml.rels":
                data = pres_rels.encode()
            elif item.filename == "[Content_Types].xml":
                data = content_types.encode()
            elif re.search(r"slide(Layouts|Masters)/slide\w+\d+\.xml$", item.filename):
                data = blank_template(data.decode(), backdrop).encode()
            zout.writestr(item.filename, data)
        for n, xml in zip(numbers, slides):
            zout.writestr(f"ppt/slides/slide{n}.xml", xml)
            zout.writestr(f"ppt/slides/_rels/slide{n}.xml.rels", base_rels)


#: "Cancel", as PowerPoint's repair dialog spells it in the localisations likely to be
#: met.  Escape does not dismiss that dialog; only a real button click does.
CANCEL_LABELS = ("Annuleren", "Cancel", "Abbrechen", "Annuler", "Cancelar", "Annulla",
                 "Avbryt", "Anuluj", "\u041e\u0442\u043c\u0435\u043d\u0430",
                 "\u30ad\u30e3\u30f3\u30bb\u30eb", "\u53d6\u6d88", "\ucde8\uc18c")

DISMISS = """
tell application "System Events"
  tell process "Microsoft PowerPoint"
    repeat with w in windows
      repeat with label in {%s}
        try
          click button label of w
          return "clicked"
        end try
      end repeat
    end repeat
    return "none"
  end tell
end tell
"""


def unwedge() -> None:
    """Clear a modal dialog, restarting PowerPoint if that does not work.

    A deck PowerPoint wants to repair puts up an app-modal dialog, and until it is
    cleared *every* export fails -- including ones for files that are perfectly fine --
    so one bad run otherwise looks like a broken environment.  The export script cannot
    clear it: it is blocked inside `open` and never regains control.
    """
    labels = ", ".join('"%s"' % label for label in CANCEL_LABELS)
    try:
        clicked = subprocess.run(
            ["osascript", "-e", DISMISS % labels],
            capture_output=True, text=True, timeout=30,
        ).stdout.strip()
    except subprocess.TimeoutExpired:
        clicked = ""
    if clicked == "clicked":
        return
    # Needs Accessibility permission; without it, restarting is the fallback.
    subprocess.run(["pkill", "-x", "Microsoft PowerPoint"], capture_output=True)
    time.sleep(3)
    subprocess.run(["open", "-g", "-a", "/Applications/Microsoft PowerPoint.app"],
                   capture_output=True)
    time.sleep(8)


def export_pdf(deck: Path, pdf: Path, attempts: int = 2) -> None:
    detail = ""
    for attempt in range(attempts):
        pdf.unlink(missing_ok=True)
        try:
            completed = subprocess.run(
                ["osascript", str(EXPORT_SCRIPT), str(deck), str(pdf)],
                capture_output=True, text=True, timeout=900,
            )
            detail = (completed.stderr or completed.stdout).strip()
        except subprocess.TimeoutExpired:
            detail = "osascript did not return"
        if pdf.exists() and pdf.stat().st_size:
            return
        print(f"  export of {deck.name} failed ({detail}); clearing PowerPoint")
        unwedge()
    raise RuntimeError(
        f"PowerPoint did not export {deck.name}: {detail}\n"
        "If this is error -9074, check for a modal dialog in PowerPoint and that "
        f"both paths are under {Path.home()}."
    )


def render(pdf: Path):
    import pypdfium2 as pdfium

    document = pdfium.PdfDocument(str(pdf))
    for index in range(len(document)):
        page = document[index]
        yield page.render(scale=WIDTH / page.get_size()[0]).to_pil().convert("RGB").load()


