#!/usr/bin/env python3
"""Derive PowerPoint's built-in table styles by measuring its own rendering.

PowerPoint keeps the built-in table styles inside the application: a deck that uses one
records only its GUID, and ``ppt/tableStyles.xml`` holds custom styles and a default id
and nothing else.  There is no file on this machine to read the definitions out of --
they were looked for.  So this script asks PowerPoint to draw them and reads the answer
back off the pixels.

It runs in three stages:

1. **A swatch sheet** -- one slide of small rectangles, each filled with a known OOXML
   colour expression (``accent1``, ``accent1`` + ``tint 40%``, ``lt2`` + ``lumMod 60%``,
   ...).  Rendering it through PowerPoint yields an exact colour-to-expression
   dictionary, so a colour sampled later can be *named* rather than approximated.  It
   also pins down PowerPoint's own transform maths, which is how the linear-light
   tint/shade behaviour in ``resolve/color.py`` was established.

2. **A style probe** -- one slide per candidate GUID, each carrying three tables laid out
   so that every conditional region lands at a known row and column:

   =======  =======================================================================
   table A  6x5, ``firstRow``/``lastRow``/``firstCol``/``lastCol``/``bandRow``:
            exposes the header, the footer, both edge columns, horizontal banding
            and all four corner cells
   table B  4x6, ``bandCol`` only: isolates vertical banding
   table C  3x3, no flags: the whole-table style, unobstructed
   =======  =======================================================================

   The probe is exported twice, over a white slide background and over a black one.  A
   composited colour then gives two equations in two unknowns::

       observed = colour * alpha + backdrop * (1 - alpha)

   so alpha falls out instead of being guessed -- which matters, because the entire
   Light Style family bands with 20%-alpha black rather than with an opaque grey, and a
   single backdrop cannot tell those apart.  A cell that tracks the backdrop exactly has
   no fill at all.

3. **Inference** -- fills, stroke colours, stroke widths, text colours and bold are read
   per region, and only values that differ from what the lower-precedence regions
   already produce are kept, so the output is overrides and nothing else.

Two checks keep guesses out of the result.  A GUID PowerPoint does not recognise renders
exactly like "No Style, Table Grid" -- that is its fallback -- so a candidate measuring
identical to the fallback is a wrong GUID and is dropped.  And within a family the six
accent variants are generated by PowerPoint from one template, so any disagreement
between them is a measurement artefact and the minority is rewritten from the majority.

Usage (macOS, with PowerPoint installed)::

    python3 tools/derive_table_styles.py --all
    python3 tools/derive_table_styles.py --emit > body.py

Needs ``pypdfium2`` and ``pillow`` to rasterise the exports; neither is a dependency of
the library itself, which is why this lives in ``tools/`` and not in ``src/``.
"""

