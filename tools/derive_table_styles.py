#: name, x, y, column width, columns, row height, rows, `a:tblPr` flags
PROBE_TABLES = [
    ("A", 300000, 150000, 1400000, 5, 400000, 6,
     'firstRow="1" lastRow="1" firstCol="1" lastCol="1" bandRow="1"'),
    ("B", 300000, 2750000, 1100000, 6, 300000, 4, 'bandCol="1"'),
    ("C", 300000, 4100000, 800000, 3, 300000, 3, ""),
]
#: Something with plenty of vertical stems, so ink coverage separates bold from regular.
PROBE_TEXT = "HHHH"


def probe_slide(guid: str, backdrop: str) -> tuple[str, dict]:
    frames, index = [], {}
    for i, (tag, x, y, col_w, cols, row_h, rows, flags) in enumerate(PROBE_TABLES):
        cell = (
            '<a:tc><a:txBody><a:bodyPr/><a:lstStyle/>'
            '<a:p><a:pPr algn="l" marL="0" indent="0"><a:buNone/></a:pPr>'
            f'<a:r><a:rPr lang="en-US" sz="800"/><a:t>{PROBE_TEXT}</a:t></a:r></a:p>'
            '</a:txBody><a:tcPr marL="0" marR="0" marT="0" marB="0" anchor="ctr"/></a:tc>'
        )
        body = []
        for r in range(rows):
            body.append(f'<a:tr h="{row_h}">' + cell * cols + "</a:tr>")
            for c in range(cols):
                index[f"{tag}:{r}:{c}"] = {
                    "x": x + c * col_w, "y": y + r * row_h, "w": col_w, "h": row_h
                }
        frames.append(
            f'<p:graphicFrame><p:nvGraphicFramePr><p:cNvPr id="{300 + i}" name="{tag}"/>'
            '<p:cNvGraphicFramePr/><p:nvPr/></p:nvGraphicFramePr>'
            f'<p:xfrm><a:off x="{x}" y="{y}"/>'
            f'<a:ext cx="{col_w * cols}" cy="{row_h * rows}"/></p:xfrm>'
            '<a:graphic><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/table">'
            f'<a:tbl><a:tblPr {flags}><a:tableStyleId>{guid}</a:tableStyleId></a:tblPr>'
            + f'<a:tblGrid>{f"""<a:gridCol w="{col_w}"/>""" * cols}</a:tblGrid>'
            + "".join(body)
            + "</a:tbl></a:graphicData></a:graphic></p:graphicFrame>"
        )
    return slide_document(backdrop, "".join(frames)), index


def build_probe(source: Path) -> dict:
    index = {}
    for backdrop in BACKDROPS:
        slides = []
        for number, (guid, name) in enumerate(CANDIDATES, start=1):
            xml, cells = probe_slide(guid, backdrop)
            slides.append(xml)
            index[str(number)] = {"guid": guid, "name": name, "cells": cells}
        write_deck(source, WORK / f"probe-{backdrop}.pptx", slides, backdrop)
    (WORK / "probe-index.json").write_text(json.dumps(index), encoding="utf-8")
    return index


