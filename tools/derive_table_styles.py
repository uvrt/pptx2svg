# Measurement
# --------------------------------------------------------------------------------------


def distance(a, b) -> int:
    return sum(abs(int(p) - int(q)) for p, q in zip(a, b))


def snap(value, choices):
    return min(choices, key=lambda candidate: abs(candidate - value))


def match(candidates, over_white, over_black):
    """Identify a paint from the same spot rendered over white and over black.

    Dividing the black-backed sample by alpha to recover the colour amplifies its
    rounding error fivefold at 20% alpha, which is enough to turn `accent1` into
    `accent1 shade 95%`.  Searching (colour, alpha) pairs for the one that predicts both
    observations keeps the answer on the small set of expressions Office actually uses,
    and among equally good fits the plainest expression wins.
    """
    if max(abs(w - b) for w, b in zip(over_white, over_black)) > 240:
        return None, 0.0, 0  # tracks the backdrop exactly: no paint at all
    scored = []
    for rgb, name in candidates:
        for alpha in ALPHAS:
            error = 0
            for channel in range(3):
                painted = rgb[channel] * alpha
                error += abs(painted + 255 * (1 - alpha) - over_white[channel])
                error += abs(painted - over_black[channel])
            scored.append((error, name, alpha))
    floor = min(entry[0] for entry in scored)
    close = [entry for entry in scored if entry[0] <= floor + 6]
    error, name, alpha = min(close, key=lambda e: (simplicity(e[1]), e[0], -e[2]))
    return name, alpha, error


def stroke_in(run, window):
    """Index and run length of the stroke crossing a scan, or None when bare."""
    side_a, side_b = run[0], run[-1]
    inner = [
        i for i in range(window // 2, len(run) - window // 2)
        if distance(run[i], side_a) > 12 and distance(run[i], side_b) > 12
    ]
    if not inner:
        return None
    colour, occurrences = Counter(run[i] for i in inner).most_common(1)[0]
    if occurrences < 2:
        return None
    return next(i for i in inner if run[i] == colour), occurrences


def measure_edge(white, black, emu_x, emu_y, horizontal, candidates, window=16):
    """Colour, alpha and width of the stroke on one cell edge, or None.

    Width is coverage rather than a count of exactly-matching pixels: a 1 pt line lands
    on about three and a half pixels here, so its edges are always part-covered and
    counting whole pixels loses most of a point.
    """
    cx, cy = int(round(emu_x * SCALE)), int(round(emu_y * SCALE))
    run_white, run_black = [], []
    for offset in range(-window, window + 1):
        sx, sy = (cx, cy + offset) if horizontal else (cx + offset, cy)
        try:
            run_white.append(white[sx, sy])
            run_black.append(black[sx, sy])
        except IndexError:
            return None

    # A white stroke is invisible against the white backdrop and a black one against the
    # black backdrop, so the table's outer edges only show in one of the two renders.
    found = None
    for run in (run_white, run_black):
        candidate = stroke_in(run, window)
        if candidate is not None and (found is None or candidate[1] > found[1]):
            found = (*candidate, run)
    if found is None:
        return None
    centre, _, run = found

    name, alpha, error = match(candidates, run_white[centre], run_black[centre])
    if name is None:
        return None

    side_a, side_b, stroke = run[0], run[-1], run[centre]
    coverage = 0.0
    for i, rgb in enumerate(run):
        own = side_a if i < len(run) / 2 else side_b
        span = distance(stroke, own)
        if span:
            coverage += max(0.0, min(1.0, distance(rgb, own) / span))
    return {"color": name, "alpha": alpha, "error": error,
            "width_pt": coverage / (EMU_PER_POINT * SCALE)}


def sample(index: dict, swatches: dict) -> dict:
    for backdrop in BACKDROPS:
        export_pdf(WORK / f"probe-{backdrop}.pptx", WORK / f"probe-{backdrop}.pdf")
    white_pages = list(render(WORK / "probe-FFFFFF.pdf"))
    black_pages = list(render(WORK / "probe-000000.pdf"))
    candidates = [
        (tuple(int(hexv[i:i + 2], 16) for i in (1, 3, 5)), entries[0])
        for hexv, entries in swatches.items()
    ]

    measured = {}
    for slide_no in sorted(index, key=int):
        entry = index[slide_no]
        white, black = white_pages[int(slide_no) - 1], black_pages[int(slide_no) - 1]
        record = {"guid": entry["guid"], "name": entry["name"], "cells": {}, "edges": {}}

        for key, box in entry["cells"].items():
            x, y, w, h = box["x"], box["y"], box["w"], box["h"]
            # The right quarter of the cell is clean fill: the text never reaches it.
            fx = int(round((x + w * 0.85) * SCALE))
            fy = int(round((y + h * 0.5) * SCALE))
            paint = white[fx, fy]
            fill, alpha, fill_error = match(candidates, paint, black[fx, fy])

            x0, y0 = int((x + w * 0.02) * SCALE), int((y + h * 0.15) * SCALE)
            x1, y1 = int((x + w * 0.45) * SCALE), int((y + h * 0.85) * SCALE)
            ink = total = 0
            glyph = Counter()
            for sy in range(y0, y1):
                for sx in range(x0, x1):
                    rgb = white[sx, sy]
                    total += 1
                    if distance(rgb, paint) > 120:
                        ink += 1
                        glyph[rgb] += 1
            text_rgb = glyph.most_common(1)[0][0] if glyph else paint
            text, _, text_error = match(candidates, text_rgb, text_rgb)

            record["cells"][key] = {
                "fill": fill, "fill_alpha": alpha, "fill_error": fill_error,
                "text": text, "text_error": text_error,
                "ink": ink / total if total else 0.0,
            }

            for side, (ex, ey, horizontal) in {
                "top": (x + w * 0.6, y, True),
                "bottom": (x + w * 0.6, y + h, True),
                # Above the text, which is centred and would read as a stroke.
                "left": (x, y + h * 0.12, False),
                "right": (x + w, y + h * 0.12, False),
            }.items():
                record["edges"][f"{key}:{side}"] = measure_edge(
                    white, black, ex, ey, horizontal, candidates
                )

        measured[slide_no] = record
        print(f"  slide {slide_no:>2}  {entry['name']}", flush=True)

    (WORK / "measured.json").write_text(json.dumps(measured, indent=1), encoding="utf-8")
    return measured


