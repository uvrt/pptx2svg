SWATCH = 120000
SWATCH_COLUMNS = 40


def swatch_expressions() -> list[tuple[str, str, str]]:
    transforms = [("plain", "")]
    for value in (5, 10, 20, 25, 30, 40, 50, 60, 75, 80, 90, 95):
        transforms.append((f"tint{value}", f'<a:tint val="{value * 1000}"/>'))
        transforms.append((f"shade{value}", f'<a:shade val="{value * 1000}"/>'))
    for mod, off in ((20, 80), (40, 60), (50, 50), (60, 40), (75, 25), (50, 0), (60, 0),
                     (75, 0), (80, 0), (85, 0), (90, 0), (95, 0), (20, 0), (40, 0)):
        body = f'<a:lumMod val="{mod * 1000}"/>'
        if off:
            body += f'<a:lumOff val="{off * 1000}"/>'
        transforms.append((f"lumMod{mod}lumOff{off}", body))
    return [
        (f"{slot}:{label}", slot, body)
        for slot in SLOTS
        for label, body in transforms
    ]


def build_swatches(source: Path) -> dict[str, tuple[int, int]]:
    shapes, index = [], {}
    for i, (name, slot, body) in enumerate(swatch_expressions()):
        x = 10000 + (i % SWATCH_COLUMNS) * SWATCH
        y = 10000 + (i // SWATCH_COLUMNS) * SWATCH
        index[name] = (x + SWATCH // 2, y + SWATCH // 2)
        shapes.append(
            f'<p:sp><p:nvSpPr><p:cNvPr id="{200 + i}" name="s{i}"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>'
            f'<p:spPr><a:xfrm><a:off x="{x}" y="{y}"/><a:ext cx="{SWATCH}" cy="{SWATCH}"/></a:xfrm>'
            f'<a:prstGeom prst="rect"><a:avLst/></a:prstGeom>'
            f'<a:solidFill><a:schemeClr val="{slot}">{body}</a:schemeClr></a:solidFill>'
            f'<a:ln><a:noFill/></a:ln></p:spPr>'
            f'<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:endParaRPr/></a:p></p:txBody></p:sp>'
        )
    write_deck(source, WORK / "swatches.pptx", [slide_document("FF00FF", "".join(shapes))], "FF00FF")
    return index


