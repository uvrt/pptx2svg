def spec(name: str | None, alpha: float = 1.0) -> str | None:
    """A colour as `slot`, `slot/tint40`, `slot/alpha20` -- or None for no paint."""
    if name is None:
        return None
    slot, label = name.split(":")
    parts = [slot] + ([] if label == "plain" else [label])
    alpha = snap(alpha, ALPHAS)
    if alpha < 1.0:
        parts.append(f"alpha{int(round(alpha * 100))}")
    return "/".join(parts)


def edge_spec(edge) -> list | None:
    if edge is None:
        return None
    return [snap(edge["width_pt"], WIDTHS), spec(edge["color"], edge["alpha"])]


def infer(record: dict) -> dict:
    cells, edges = record["cells"], record["edges"]
    style = {"guid": record["guid"], "name": record["name"]}

    def fill(key):
        return spec(cells[key]["fill"], cells[key]["fill_alpha"])

    def text(key):
        return spec(cells[key]["text"])

    # Ink coverage scales with cell width, so bold is only judged against body cells of
    # the same table.  Table A's body carries the whole-table text style, which makes it
    # the "not bold" reference for every region A exercises.
    body = sorted(cells[f"A:{r}:{c}"]["ink"] for r in (1, 2, 3, 4) for c in (1, 2, 3))
    reference = body[len(body) // 2]

    def bold(key):
        return cells[key]["ink"] > reference * 1.15

    whole = {"fill": fill("C:1:1"), "text": text("C:1:1"), "bold": False, "borders": {
        "left": edge_spec(edges.get("C:1:0:left")),
        "right": edge_spec(edges.get("C:1:2:right")),
        "top": edge_spec(edges.get("C:0:1:top")),
        "bottom": edge_spec(edges.get("C:2:1:bottom")),
        "insideH": edge_spec(edges.get("C:1:1:top")),
        "insideV": edge_spec(edges.get("C:1:1:left")),
    }}
    style["wholeTbl"] = whole

    # Table A's body rows are 1..4, so the banding index is row - 1; table B bands by
    # column, so it is the column index.
    for key, sample_key in (("band1H", "A:1:2"), ("band2H", "A:2:2"),
                            ("band1V", "B:1:0"), ("band2V", "B:1:1")):
        value = fill(sample_key)
        style[key] = {"fill": value if value != whole["fill"] else None}

    def region(key, expected_fill, expected_text, borders, expected_bold=False):
        is_bold = bold(key)
        sampled_fill, sampled_text = fill(key), text(key)
        return {
            "fill": sampled_fill if sampled_fill != expected_fill else None,
            "text": sampled_text if sampled_text != expected_text else None,
            "bold": is_bold if is_bold != expected_bold else None,
            "borders": {k: v for k, v in borders.items() if v is not None},
        }

    def differs(sampled, baseline):
        return sampled if sampled != baseline else None

    inside_h, inside_v = whole["borders"]["insideH"], whole["borders"]["insideV"]
    style["firstRow"] = region("A:0:2", whole["fill"], whole["text"], {
        "bottom": differs(edge_spec(edges.get("A:0:2:bottom")), inside_h),
        "insideV": differs(edge_spec(edges.get("A:0:2:right")), inside_v),
    })
    style["lastRow"] = region("A:5:2", whole["fill"], whole["text"], {
        "top": differs(edge_spec(edges.get("A:5:2:top")), inside_h),
        "insideV": differs(edge_spec(edges.get("A:5:2:right")), inside_v),
    })
    # Row 2 of table A is a band2H row, so that is what the column regions override.
    under = style["band2H"]["fill"] or whole["fill"]
    style["firstCol"] = region("A:2:0", under, whole["text"], {
        "right": differs(edge_spec(edges.get("A:2:0:right")), inside_v)})
    style["lastCol"] = region("A:2:4", under, whole["text"], {
        "left": differs(edge_spec(edges.get("A:2:4:left")), inside_v)})

    # Corners inherit from the row regions, which outrank the column regions.
    for key, corner, row in (("A:0:0", "nwCell", "firstRow"), ("A:0:4", "neCell", "firstRow"),
                             ("A:5:0", "swCell", "lastRow"), ("A:5:4", "seCell", "lastRow")):
        style[corner] = region(
            key,
            style[row]["fill"] or whole["fill"],
            style[row]["text"] or whole["text"],
            {},
            expected_bold=bool(style[row]["bold"]),
        )
    return style


def signature(style: dict) -> str:
    return json.dumps({key: style[key] for key in REGIONS}, sort_keys=True)


def normalise_families(styles: dict, dropped: set) -> None:
    """Make each family's accent variants agree.

    PowerPoint generates them from one template, so a disagreement is a measurement
    artefact -- a colour match gone astray on a low-contrast accent, or a hairline seen
    in some accents and not others.  Rewriting the minority from the majority invents
    nothing: the majority definition is itself measured.
    """
    families = defaultdict(dict)
    for guid, style in styles.items():
        if guid in dropped:
            continue
        match_ = re.match(r"^(.*?) - Accent (\d)$", style["name"])
        if match_:
            families[match_.group(1)][guid] = match_.group(2)

    for family, members in families.items():
        shapes = defaultdict(list)
        for guid in members:
            shapes[re.sub(r"accent\d", "accentN", signature(styles[guid]))].append(guid)
        if len(shapes) < 2:
            continue
        template = max(shapes, key=lambda body: len(shapes[body]))
        for body, guids in shapes.items():
            if body == template:
                continue
            for guid in guids:
                styles[guid].update(
                    json.loads(template.replace("accentN", f"accent{members[guid]}"))
                )
                print(f"  normalised {styles[guid]['name']} to the {family} majority")


def emit(styles: dict) -> str:
    fallback = signature(styles[TABLE_GRID_GUID])
    dropped = {
        guid for guid, style in styles.items()
        if guid != TABLE_GRID_GUID and signature(style) == fallback
    }
    normalise_families(styles, dropped)
    for guid in sorted(dropped):
        print(f"  dropped {styles[guid]['name']}: PowerPoint does not know that GUID")

    lines = []
    for guid, style in styles.items():
        if guid in dropped:
            continue
        lines.append(f'    "{guid}": {{')
        lines.append(f'        "name": "{style["name"]}",')
        for name in REGIONS:
            region, parts = style[name], []
            for key in ("fill", "text"):
                if region.get(key):
                    parts.append(f'"{key}": "{region[key]}"')
            if region.get("bold"):
                parts.append('"bold": True')
            borders = {k: v for k, v in region.get("borders", {}).items() if v}
            if borders:
                parts.append(
                    '"borders": {'
                    + ", ".join(
                        f'"{side}": ({borders[side][0]}, "{borders[side][1]}")'
                        for side in SIDES if side in borders
                    )
                    + "}"
                )
            if parts:
                lines.append(f'        "{name}": {{' + ", ".join(parts) + "},")
        lines.append("    },")
    return "\n".join(lines) + "\n"


