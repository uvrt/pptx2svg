"""Advance widths for the faces this library draws with.

Rendering a PPTX faithfully needs to know how wide a string will be *before* the SVG is
handed to a rasteriser, because wrapping, autofit shrinking and vertical centring all
depend on it.  Reading the user's real fonts for that would make output depend on which
machine ran the conversion, so the numbers are baked in here.

The thing that makes them trustworthy is where they come from: every table below is
generated by ``tools/extract_font_metrics.py`` from the exact font file shipped in
:mod:`pptx2svg.fonts` (or in the optional ``pptx2svg-fonts`` distribution), which is the
file the rasteriser is handed.  **We measure with what we draw with.**  Do not edit the
generated block by hand -- ``tests/test_fonts.py`` regenerates it and fails on drift.

Before that was true the table was a copy of pptx-glimpse's
``packages/renderer/src/data/font-metrics.ts``, and by the time anyone checked, its Noto
Sans JP column disagreed with the shipped Noto Sans JP for 186 of 191 characters.  That
is the whole argument for generating it.

Two details worth knowing:

* **Bold is a separate table, not a multiplier.**  This used to scale every bold run by
  1.05.  Measured against the real bold faces that is wrong in both directions: Cousine
  (monospace) is exactly 1.000, Carlito 1.023, Caladea 1.089, Noto Sans JP 1.119.  Since
  resvg draws with the real bold face, measuring with a fudge factor guaranteed a
  mismatch on every heading in every deck.
* **Italic is not.**  Italic advance widths differ from upright by at most 2.5% across
  the Office substitutes (Carlito 0.4%, Tinos 2.2%, Caladea 2.5%, Arimo and Cousine
  0.0%), which is inside the noise of everything else here.  Lato is the outlier at 6%;
  that is accepted rather than doubling the table again.

Widths are in font units; divide by ``units_per_em`` and multiply by the pixel size.
"""

